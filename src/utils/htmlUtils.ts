/**
 * Escapes a string for safe use inside an HTML text node or attribute.
 * @param value Raw string
 * @returns The escaped string
 */
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
